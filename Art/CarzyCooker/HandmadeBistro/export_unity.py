"""Pack authored frames into a separate runtime atlas and generate its C# layout."""
import csv
import math
import sys
from pathlib import Path
import bpy
import numpy as np

base = Path(__file__).resolve().parent
root = base.parents[2]
with (base / "clips.csv").open(encoding="utf-8", newline="") as stream:
    rows = list(csv.DictReader(stream))
# The existing game also has washing / beating. Reuse the authored work motion
# without its cutting knife, keeping those activities visually distinct from chopping.
bpy.ops.wm.open_mainfile(filepath=str(base / "source/HandmadeBistro.blend"))
scene = bpy.context.scene
chef = bpy.data.objects["Chef · editable transform rig"]
knife, handle = bpy.data.objects["Cutting knife blade"], bpy.data.objects["Knife wooden handle"]
# The source keys knife visibility for chopping. Remove that animation only from
# this temporary work-render scene, so render evaluation cannot reveal it again.
knife.animation_data_clear()
handle.animation_data_clear()
chop_rows = [row for row in rows if row["clip"] == "chef_chop"]
for direction, angle in zip(("north", "east", "south", "west"), (math.pi, math.pi/2, 0, -math.pi/2)):
    chef.rotation_euler.z = angle
    for frame in range(8):
        scene.frame_set(25 + frame)
        knife.hide_render = handle.hide_render = True
        frame_file = f"runtime-work/{direction}/{frame:03}.png"
        path = base / frame_file
        path.parent.mkdir(parents=True, exist_ok=True)
        scene.render.filepath = str(path)
        bpy.ops.render.render(write_still=True)
        source = next(row for row in chop_rows if row["direction"] == direction and int(row["frame"]) == frame)
        rows.append(dict(source, clip="chef_work", frame_file=frame_file))
bpy.ops.wm.open_mainfile(filepath=str(base / "source/HandmadeBistro.blend"))
scene = bpy.context.scene
scene.frame_set(1)
sys.path.insert(0, str(base))
from coherence_models import export_sample
sample_rows, sample_spans = export_sample(base, scene, rows[0])
rows.extend(sample_rows)
cell, columns = 192, 16
height = math.ceil(len(rows) / columns)
atlas = np.zeros((height * cell, columns * cell, 4), dtype=np.float32)
starts = {}
hands = []
for index, row in enumerate(rows):
    starts.setdefault(row["clip"], index)
    image = bpy.data.images.load(str(base / row["frame_file"]), check_existing=False)
    assert tuple(image.size) == (cell, cell)
    pixels = np.empty(cell * cell * 4, dtype=np.float32)
    image.pixels.foreach_get(pixels)
    bpy.data.images.remove(image)
    y, x = divmod(index, columns)
    atlas[y * cell:(y + 1) * cell, x * cell:(x + 1) * cell] = pixels.reshape(cell, cell, 4)
    hands.append((float(row["hand_x_from_left"]), float(row["hand_y_from_bottom"])))
target = root / "Unity/Assets/Res/Entity/Product/Art/BistroAtlas.png"
target.parent.mkdir(parents=True, exist_ok=True)
image = bpy.data.images.new("BistroAtlas", width=columns * cell, height=height * cell, alpha=True)
image.pixels.foreach_set(atlas.reshape(-1))
image.filepath_raw, image.file_format = str(target), "PNG"
image.save()
layout = root / "Unity/Assets/Scripts/Game/ET/Code/ModelView/Client/Product/GridKitchen/MonoGridKitchenBoard.BistroLayout.cs"
names = {"chef_idle": "Idle", "chef_walk": "Walk", "chef_carry": "Carry", "chef_chop": "Chop", "chef_serve": "Serve",
    "soup_loop": "Soup", "juice_loop": "Juice", "steam_loop": "Steam", "bowl_empty": "Bowl", "pot_empty": "Pot",
    "cup_empty": "Cup", "plate_empty": "Plate", "toast": "Toast", "station_prep": "Chopping", "station_hob": "Stove",
    "station_sink": "Wash", "window": "Window", "herb_pot": "Plant", "chef_work": "Work",
    "tomato": "Tomato", "tomato_chunks": "TomatoChunks", "egg": "Egg", "egg_liquid": "EggLiquid",
    "bread": "Bread", "station_oven": "Oven"}
spans = [1.95] * 160 + [1.0] * 8 + [.8] * 8 + [1.05] * 8 + [1.15, 1.3, 1.05, 1.15, 1.0] + [1.7] * 12 + [1.4, .95] + [1.95] * 32
spans.extend(sample_spans)
assert len(spans) == len(rows) == len(hands) == 244
lines = ["// <auto-generated> Art/CarzyCooker/HandmadeBistro/export_unity.py; do not edit. </auto-generated>",
    "using UnityEngine;", "namespace ET.Client", "{", "    public partial class MonoGridKitchenBoard", "    {",
    f"        private const int BistroCell = {cell}, BistroColumns = {columns}, BistroRows = {height}, BistroCount = {len(rows)};",
    f"        private const float BistroFootY = {float(rows[0]['pivot_y_from_bottom']):.5f}f;"]
for clip, start in starts.items():
    lines.append(f"        private const int Bistro{names[clip]} = {start};")
lines.append("        private static readonly float[] BistroSpans = new float[] { " + ", ".join(f"{v:g}f" for v in spans) + " };")
lines.append("        private static readonly Vector2[] BistroHands = new Vector2[]")
lines.append("        {")
for x, y in hands:
    lines.append(f"            new Vector2({x:.5f}f, {y:.5f}f),")
lines.extend(["        };", "    }", "}", ""])
layout.write_text("\n".join(lines), encoding="utf-8")
with (base / "runtime-layout.csv").open("w", encoding="utf-8", newline="") as stream:
    writer = csv.DictWriter(stream, fieldnames=[*rows[0].keys(), "runtime_index", "runtime_span"])
    writer.writeheader()
    writer.writerows(dict(row, runtime_index=index, runtime_span=spans[index]) for index, row in enumerate(rows))
print(f"BISTRO UNITY EXPORT COMPLETE frames={len(rows)} atlas={columns*cell}x{height*cell} hands={len(hands)}", flush=True)
